/**
 * 하루·주 범위 해석 (specs/020 contracts/date-param.md §3)
 * 오늘 = 2026-10-23(금). 주는 월~일.
 */
const path = require("path");
const { freezeClock } = require("./helpers/hrHandlerHarness");
const { resolveDateRange, inRange, monthsOf } = require(path.resolve(
  __dirname,
  "../../../../storage/plugins/agent-skills/_shared/dateRange.js"
));

const NOW = new Date("2026-10-23T10:00:00+09:00");

describe("resolveDateRange", () => {
  beforeAll(() => freezeClock(NOW));
  afterAll(() => jest.useRealTimers());

  it.each([
    ["오늘", "20261023", "20261023", "day", "오늘(10/23)"],
    ["금일", "20261023", "20261023", "day", "오늘(10/23)"],
    ["어제", "20261022", "20261022", "day", "어제(10/22)"],
    ["그저께", "20261021", "20261021", "day", "그저께(10/21)"],
    ["그제", "20261021", "20261021", "day", "그저께(10/21)"],
    ["내일", "20261024", "20261024", "day", "내일(10/24)"],
    ["모레", "20261025", "20261025", "day", "모레(10/25)"],
    ["10월 15일", "20261015", "20261015", "day", "10월 15일"],
    ["15일", "20261015", "20261015", "day", "10월 15일"],
    ["20261015", "20261015", "20261015", "day", "10월 15일"],
    ["2026-10-15", "20261015", "20261015", "day", "10월 15일"],
    ["10/15", "20261015", "20261015", "day", "10월 15일"],
    ["2025년 3월 2일", "20250302", "20250302", "day", "2025년 3월 2일"],
    ["이번 주", "20261019", "20261025", "week", "이번 주(10/19~10/25)"],
    ["이번주", "20261019", "20261025", "week", "이번 주(10/19~10/25)"],
    ["금주", "20261019", "20261025", "week", "이번 주(10/19~10/25)"],
    ["지난주", "20261012", "20261018", "week", "지난주(10/12~10/18)"],
    ["저번 주", "20261012", "20261018", "week", "지난주(10/12~10/18)"],
    ["다음 주", "20261026", "20261101", "week", "다음 주(10/26~11/1)"],
    ["차주", "20261026", "20261101", "week", "다음 주(10/26~11/1)"],
    // "자" 접미사(코드 리뷰 M5)
    ["오늘자", "20261023", "20261023", "day", "오늘(10/23)"],
    ["10월 15일자", "20261015", "20261015", "day", "10월 15일"],
    // 요일 표현 — 그 주의 그 요일(D14, 사용자 요청 2026-10-23)
    ["이번 주 수요일", "20261021", "20261021", "day", "이번 주 수요일(10/21)"],
    ["이번주 수요일", "20261021", "20261021", "day", "이번 주 수요일(10/21)"],
    ["수요일", "20261021", "20261021", "day", "이번 주 수요일(10/21)"],
    ["금주 금요일", "20261023", "20261023", "day", "이번 주 금요일(10/23)"],
    ["지난주 월요일", "20261012", "20261012", "day", "지난주 월요일(10/12)"],
    ["저번 주 월요일", "20261012", "20261012", "day", "지난주 월요일(10/12)"],
    ["지난 월요일", "20261012", "20261012", "day", "지난주 월요일(10/12)"],
    ["다음 주 금요일", "20261030", "20261030", "day", "다음 주 금요일(10/30)"],
    ["차주 화요일", "20261027", "20261027", "day", "다음 주 화요일(10/27)"],
    ["이번 주 일요일", "20261025", "20261025", "day", "이번 주 일요일(10/25)"],
    // 연도 없는 날짜가 6개월 안이면 올해 그대로(D12)
    ["11월 5일", "20261105", "20261105", "day", "11월 5일"],
    ["4월 1일", "20260401", "20260401", "day", "4월 1일"],
  ])("%p → %s~%s", (input, start, end, kind, label) => {
    expect(resolveDateRange(input, NOW)).toEqual({ start, end, kind, label });
  });

  it.each([[undefined], [null], [""], ["  "], ["최근"], ["전체"]])("지정 없음 %p → undefined", (v) => {
    expect(resolveDateRange(v, NOW)).toBeUndefined();
  });

  it.each([["저번 분기"], ["abc"], ["10월 32일"], ["상반기"], ["10월"], ["이번 달"]])(
    "하루·주가 아닌 값 %p → null(해석 실패)",
    (v) => {
      expect(resolveDateRange(v, NOW)).toBeNull();
    }
  );
});

describe("연도 없는 날짜가 6개월 넘게 뒤면 작년 (D12, 사용자 결정 2026-10-23)", () => {
  const JAN2 = new Date("2027-01-02T10:00:00+09:00");
  beforeAll(() => freezeClock(JAN2));
  afterAll(() => jest.useRealTimers());

  it.each([["12월 31일"], ["12/31"], ["12월 31일자"]])("1월 2일에 %p → 작년 12/31", (v) => {
    expect(resolveDateRange(v, JAN2)).toEqual({
      start: "20261231", end: "20261231", kind: "day", label: "2026년 12월 31일",
    });
  });

  it("1월 2일에 \"1월 10일\"(가까운 미래)은 올해 그대로", () => {
    expect(resolveDateRange("1월 10일", JAN2).start).toBe("20270110");
  });

  it("연도를 말하면 그대로(\"2027년 12월 31일\")", () => {
    expect(resolveDateRange("2027년 12월 31일", JAN2).start).toBe("20271231");
  });
});

describe("범위 헬퍼", () => {
  it("inRange — 8자리 날짜가 범위 안인지", () => {
    const r = { start: "20261019", end: "20261025" };
    expect(inRange("20261019", r)).toBe(true);
    expect(inRange("20261025", r)).toBe(true);
    expect(inRange("20261026", r)).toBe(false);
    expect(inRange(null, r)).toBe(false);
  });

  it("monthsOf — 범위가 걸친 달(YYYYMM), 두 달에 걸친 주 포함", () => {
    expect(monthsOf({ start: "20261019", end: "20261025" })).toEqual(["202610"]);
    expect(monthsOf({ start: "20260928", end: "20261004" })).toEqual(["202609", "202610"]);
  });
});
